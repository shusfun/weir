require('./production-guard.cjs');
const { chromium } = require('playwright');
const fs = require('fs'), path = require('path');
let browser;
(async () => {
 const state = JSON.parse(fs.readFileSync(path.join(process.env.LOCALAPPDATA, 'MiGate/operations/deployment.json'), 'utf8'));
 browser = await chromium.launch({ channel: 'chrome', args: ['--no-proxy-server', '--host-resolver-rules=MAP sub.caowo.baby 127.0.0.1:19443'] });
 const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
 await context.addCookies([{ name: 'migate_session', value: state.admin_cookie.slice('migate_session='.length), domain: 'sub.caowo.baby', path: '/', secure: true, httpOnly: true }]);
 const page = await context.newPage(), errors = [], checks = [];
 page.on('pageerror', e => errors.push(e.message));
 const requests = [];
 page.on('request', r => { if (r.url().includes('/api/v1/')) requests.push(new URL(r.url()).pathname); });
 await page.goto('https://sub.caowo.baby/audit');
 await page.getByRole('heading', { name: '操作记录', exact: true }).waitFor();
 await page.getByRole('button', { name: /^查看记录 #/ }).first().waitFor();
 await page.getByRole('button', { name: '下一页', exact: true }).click();
 await page.getByText(/第 2 页/).waitFor();
 await page.getByRole('button', { name: '上一页', exact: true }).click();
 const search = page.getByLabel('搜索审计记录');
 await search.fill('task.');
 await page.getByRole('button', { name: /^查看记录 #/ }).first().waitFor();
 await page.getByRole('button', { name: /^查看记录 #/ }).first().click();
 await page.getByRole('dialog').getByRole('link', { name: '查看关联任务' }).click();
 await page.getByRole('heading', { name: '执行记录与回执' }).waitFor();
 if (!(await page.getByLabel('搜索执行任务').inputValue())) throw Error('Task correlation lost on deep link');
 await page.getByRole('button', { name: /^查看回执 #/ }).first().waitFor();
 checks.push('real audit pagination, search, detail and task deep-link preserve correlated task number');
 await page.goto('https://sub.caowo.baby/audit');
 await page.getByLabel('筛选审计结果').click();
 await page.getByRole('option', { name: '拒绝', exact: true }).click();
 await page.getByRole('button', { name: /^查看记录 #/ }).first().waitFor();
 for (const width of [1440, 1280, 768, 390]) {
  await page.setViewportSize({ width, height: 1000 });
  await page.screenshot({ path: `docs/evidence/audit-live-${width}.png`, fullPage: true });
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw Error('Audit overflow at ' + width);
 }
 await search.fill('no-audit-record-' + Date.now());
 await page.getByText('没有符合条件的操作记录', { exact: true }).waitFor();
 checks.push('result filter, four widths and real empty search');
 await page.route('**/api/v1/admin/audit?**', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { code: 'audit_unavailable' } }) }));
 await page.getByRole('button', { name: '刷新记录', exact: true }).click();
 await page.getByText('暂时无法加载', { exact: true }).waitFor();
 await page.screenshot({ path: 'docs/evidence/audit-error-390.png', fullPage: true });
 await page.unroute('**/api/v1/admin/audit?**');
 await page.getByLabel('筛选审计结果').click();
 await page.getByRole('option', { name: '全部结果', exact: true }).click();
 await search.fill('task.');
 await page.getByRole('button', { name: '重新加载', exact: true }).click().catch(() => {});
 await page.getByRole('button', { name: /^查看记录 #/ }).first().waitFor();
 checks.push('browser-injected 503 displays retry state and recovers to actual backend records; not a real server outage');
 requests.length = 0;
 await page.goto('https://sub.caowo.baby/users');
 await page.getByRole('heading', { name: '账户与访问权限', exact: true }).waitFor();
 const userRequests = requests.filter(p => p === '/api/v1/admin/users');
 if (userRequests.length !== 1) throw Error('Users route has duplicate legacy directory requests: ' + userRequests.length);
 checks.push('independent route loads user directory once without legacy prerequisite');
 if (errors.length) throw Error('Browser runtime error');
 const version = await page.evaluate(async () => (await (await fetch('/api/v1/admin/overview')).json()).version);
 fs.writeFileSync('docs/evidence/audit-live.json', JSON.stringify({ version, date: new Date().toISOString(), checks }, null, 2));
 await browser.close(); console.log('Real audit search, paging, result filter, task correlation, empty/error recovery and route request isolation passed');
})().catch(async e => { if (browser) await browser.close(); console.error(e.message); process.exitCode = 1; });
