export function contextGuide(path: string, context: CtxLayer, identity: GuideIdentity): Guide | null {
  const guide = resolveGuide(path, context, identity);
  return guide ? { ...guide, version: versions[guide.id] ?? guide.version } : null;
}
function resolveGuide(path: string, context: CtxLayer, identity: GuideIdentity): Guide | null {
  if (path.startsWith("/dev/")) return null;
  const dialog = context.dialog?.title;
  if (dialog) {
    const detail = dialog === "VPS 详情" && context.dialog?.step;
    if (detail) {
      const help: Record<string, string> = { "概览": "查看 CPU、内存、流量历史、防火墙和已占用端口；缺少数据保持未知。云安全组需另行核对，Weir 不自动修改防火墙。", "节点与出口": "核对这台 VPS 的入站与实际出口关系，点节点可查看端口及完整实测。候选出口验证通过后才应用。", "内核": "可为这台 VPS 锁定内核版本，不锁定时使用默认版本。诊断查看真实运行结果；重启或切换后等待配置回执。", "证书": "管理此 VPS 的代理节点证书，核对域名、有效期和续签状态。控制台 HTTPS 证书由反代单独配置。" };
      return { id: `dialog:vps:${detail}`, version: 1, title: `VPS 详情 · ${detail}`, steps: [step("tab", detail, help[detail] ?? "核对当前分区说明与实际状态。", "tab-panel")] };
    }
    const steps = dialogs[dialog];
    if (steps) return { id: `dialog:${dialog}`, version: 1, title: dialog, steps };
    return { id: `dialog:${path}:help`, version: 1, title: dialog, steps: [step("dialog", dialog, "查看当前对象与说明，按需要填写或选择。教程不会替你提交修改；关闭教程会保留填写内容。", "dialog"), step("result", "确认操作结果", "提交后检查校验提示和任务最终结果。涉及删除、恢复、更新或凭据变更时，先阅读业务确认说明。", "dialog")] };
  }
  if (context.page === "初始化") return { id: "setup", version: 1, title: "安装初始化", steps: [onboarding.steps[0], onboarding.steps[1], step("setup", "完成初始化", "依次验证初始化凭证、选择存储、创建管理员。新手默认 SQLite 即可；如果库里已有账户，应恢复原配置，不能重新初始化。", "auth-content")] };
  if (identity.role === "guest" && !path.startsWith("/sub/") && !path.startsWith("/p/")) return { id: `auth:${context.tab ?? "login"}`, version: 4, title: "登录与账户", steps: [step("login", "登录自己的账户", "输入邮箱和密码；支持条件式界面且存有本站通行密钥时，邮箱框会提供密钥登录。需要二次验证时输入自己的验证码。邮件未配置时不显示找回密码。注册要求邀请码时请向管理员索取；发验证码先校验邀请，注册成功才占用。初始套餐与默认链接一并创建；没有套餐的新用户默认没有流量。需要邮箱验证时在注册表单发码、填码；允许的后缀会列在表单中。注册、发码、重置密码及连续登录失败后要求人机验证；过期后按提示重试。", "auth-content"), step("prepare", "还没安装？", onboarding.steps[0].text + " " + onboarding.steps[1].text)] };
  if (path.startsWith("/sub/")) return { id: "public-import", version: 2, title: "导入订阅", steps: [step("import", "选择自己的客户端", "先选设备，再选兼容客户端，安装后使用页面的复制或一键导入操作。地址和二维码包含订阅凭证，不要公开。", "public-content"), step("verify", "更新并测试", "在客户端更新订阅、选择节点并启用代理，实际访问核对连接。若页面不可用，请登录控制台的订阅链接页，或联系管理员。", "public-content")] };
  if (path.startsWith("/p/")) return { id: "public-page", version: 2, title: "公开页面", steps: [step("browse", "浏览公开内容", "这里由管理员发布内容。有订阅时先选设备和客户端，再导入、复制或下载；只显示兼容已发布格式的客户端。使用明确公开的分享入口；你的控制台账号和管理权限不会因此公开。", "public-content")] };
  const info = pages[path];
  if (!info) return null;
  const allowed = ["/links", "/proxy", "/security", "/my/linkmap"];
  if (identity.role !== "admin" && !allowed.includes(path)) return null;
  const guide = overview(`page:${path}`, info[0], info[1], info[2]);
  const tab = context.tab;
  const detail = tab && tabs[path]?.[tab];
  if (tab) {
    guide.id += `:${tab}`;
    guide.title += ` · ${tab}`;
    guide.steps.push(step("tab", detail?.[0] ?? tab, detail?.[1] ?? `当前是「${tab}」。先查看状态和说明，再使用这里的操作；没有数据时按页面提示添加，失败时保留当前内容并查看原因。`, "tab-panel"));
  }
  return guide;
}
