require('./production-guard.cjs');
const {chromium}=require('playwright');
const fs=require('node:fs'),path=require('node:path');
let browser;
(async()=>{
 const state=JSON.parse(fs.readFileSync(path.join(process.env.LOCALAPPDATA,'MiGate/operations/deployment.json'),'utf8'));
 const user=state.test_users[0];
 browser=await chromium.launch({channel:'chrome',headless:true,args:['--no-proxy-server','--host-resolver-rules=MAP sub.caowo.baby 127.0.0.1:19443']});
 const page=await browser.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const cdp=await page.context().newCDPSession(page);await cdp.send('WebAuthn.enable');
 await cdp.send('WebAuthn.addVirtualAuthenticator',{options:{protocol:'ctap2',transport:'internal',hasResidentKey:true,hasUserVerification:true,isUserVerified:true,automaticPresenceSimulation:true}});
 await page.goto('https://sub.caowo.baby');
 await page.getByLabel('邮箱',{exact:true}).fill(user.email);await page.getByLabel('密码',{exact:true}).fill(user.password);await page.getByRole('button',{name:/^(登录|验证并登录)$/,exact:true}).click();
 await page.getByRole('heading',{name:'我的订阅',exact:true}).waitFor();
 await page.getByRole('button',{name:'账户安全',exact:true}).click();
 await page.locator('#security-password').fill(user.password);
 await page.getByRole('button',{name:'绑定 Passkey',exact:true}).click();
 await page.getByText('Passkey 已绑定',{exact:true}).waitFor();
 const registered=await page.evaluate(async()=>await (await fetch('/api/v1/security/passkeys')).json());
 if(registered.items.length!==1)throw Error('Unexpected passkey inventory');
 await page.locator('.topbar').getByRole('button',{name:'退出',exact:true}).click();
 await page.getByLabel('邮箱',{exact:true}).fill(user.email);
 await page.getByRole('button',{name:'使用 Passkey',exact:true}).click();
 await page.getByRole('heading',{name:'我的订阅',exact:true}).waitFor();
 const forbidden=await page.evaluate(async()=>(await fetch('/api/v1/admin/users')).status);
 if(forbidden!==403)throw Error('Passkey changed user role');
 const removed=await page.evaluate(async({id,password})=>(await fetch('/api/v1/security/passkeys/'+id,{method:'DELETE',headers:{'Content-Type':'application/json'},body:JSON.stringify({password})})).status,{id:registered.items[0].id,password:user.password});
 if(removed!==200)throw Error('Failed to remove test authenticator');
 if(await page.evaluate(async()=>(await fetch('/api/v1/me')).status)!==401)throw Error('Deleting passkey did not revoke session');
 if(errors.length)throw Error(errors.join('\n'));
 fs.writeFileSync('docs/evidence/live-passkey.json',JSON.stringify({date:new Date().toISOString(),checks:['real HTTPS origin registration','browser WebAuthn assertion login','ordinary user admin API forbidden','credential deletion revokes session'],authenticator:'Chrome CDP virtual CTAP2 authenticator; user verification required',limitations:'Not a physical phone or hardware authenticator test',passed:true},null,2));
 console.log('Real server browser Passkey flow passed using virtual CTAP2 authenticator');
 await browser.close();
})().catch(async error=>{if(browser)await browser.close();console.error(error.message);process.exitCode=1});
